from odoo import _, api, fields, models, SUPERUSER_ID
from odoo.exceptions import AccessError, UserError


class CashTransfer(models.Model):
    _name = "cash.custody.transfer"
    _description = "Cash custody handover history"
    _order = "id desc"
    _check_company_auto = True

    payment_id = fields.Many2one("account.payment", required=True, ondelete="restrict", check_company=True)
    company_id = fields.Many2one("res.company", required=True)
    currency_id = fields.Many2one("res.currency", required=True)
    amount = fields.Monetary(required=True)
    date = fields.Datetime(required=True, default=fields.Datetime.now)
    actor_id = fields.Many2one("res.users", required=True)
    from_name = fields.Char(readonly=True)
    to_name = fields.Char(required=True, readonly=True)
    stage = fields.Selection([("collected", "Collector"), ("coach", "Coach"), ("manager", "Manager")], required=True)

    @api.model_create_multi
    def create(self, vals_list):
        if not self.env.su:
            raise AccessError(_("Cash handover history is generated by the handover actions."))
        return super().create(vals_list)

    def write(self, vals):
        raise AccessError(_("Cash handover history cannot be edited."))

    def unlink(self):
        raise AccessError(_("Cash handover history cannot be deleted."))


class AccountPayment(models.Model):
    _inherit = "account.payment"

    cash_collector_user_id = fields.Many2one("res.users", string="Collected By", readonly=True, copy=False)
    cash_collector_employee_id = fields.Many2one("hr.employee", readonly=True, copy=False)
    cash_holder_user_id = fields.Many2one("res.users", readonly=True, copy=False)
    cash_holder_employee_id = fields.Many2one("hr.employee", readonly=True, copy=False)
    cash_holder_name = fields.Char(compute="_compute_cash_holder_name", string="Cash Currently With")
    cash_stage = fields.Selection([("collected", "Collector"), ("coach", "Coach"), ("manager", "Manager")], readonly=True, copy=False)
    cash_transfer_ids = fields.One2many("cash.custody.transfer", "payment_id", readonly=True, copy=False)
    can_handover_cash = fields.Boolean(compute="_compute_cash_controls")

    _cash_private_fields = {"cash_collector_user_id", "cash_collector_employee_id", "cash_holder_user_id",
                            "cash_holder_employee_id", "cash_stage"}

    @api.model_create_multi
    def create(self, vals_list):
        prepared = []
        for values in vals_list:
            values = dict(values)
            collector = values.get("cash_collector_user_id") or self.env.context.get("default_cash_collector_user_id") or self.env.uid
            if not self.env.su and collector != self.env.uid:
                raise AccessError(_("A payment must record the user who actually collected it."))
            if {"cash_holder_user_id", "cash_holder_employee_id", "cash_stage", "cash_collector_employee_id"}.intersection(values):
                raise AccessError(_("Cash custody is initialized when the payment is posted."))
            for name in self._cash_private_fields - {"cash_collector_user_id"}:
                values[name] = False
            values["cash_collector_user_id"] = collector
            prepared.append(values)
        return super().create(prepared)

    def write(self, vals):
        if self._cash_private_fields.intersection(vals):
            raise AccessError(_("Use the cash handover actions to change cash custody."))
        return super().write(vals)

    @api.depends("cash_holder_employee_id.name", "cash_holder_user_id.name")
    def _compute_cash_holder_name(self):
        for payment in self:
            payment.cash_holder_name = payment.cash_holder_employee_id.sudo().name or payment.cash_holder_user_id.name

    @api.depends("state", "cash_stage", "cash_holder_user_id", "journal_id.type", "payment_type")
    @api.depends_context("uid")
    def _compute_cash_controls(self):
        for payment in self:
            payment.can_handover_cash = payment._cash_can_transfer(self.env.user)

    def _cash_can_transfer(self, actor):
        self.ensure_one()
        return bool(self.state == "posted" and self.journal_id.type == "cash" and self.payment_type == "inbound"
                    and self.cash_stage and (self.cash_holder_user_id.id == actor.id or actor.id == SUPERUSER_ID
                                            or actor.has_group("account.group_account_manager")))

    def _cash_employee_for(self, user):
        self.ensure_one()
        employees = self.env["hr.employee"].sudo().search([("user_id", "=", user.id), ("company_id", "=", self.company_id.id)])
        return employees if len(employees) == 1 else self.env["hr.employee"]

    def _cash_write_state(self, values):
        # Public write never accepts custody fields, including for sudo callers.
        return super(AccountPayment, self.sudo()).write(values)

    def _initialize_cash_custody(self):
        for payment in self.filtered(lambda pay: pay.journal_id.type == "cash" and pay.payment_type == "inbound" and not pay.cash_stage):
            collector = payment.cash_collector_user_id or payment.create_uid
            employee = payment._cash_employee_for(collector)
            payment._cash_write_state({"cash_collector_employee_id": employee.id, "cash_holder_employee_id": employee.id,
                                       "cash_holder_user_id": collector.id, "cash_stage": "collected"})
            self.env["cash.custody.transfer"].sudo().create({
                "payment_id": payment.id, "company_id": payment.company_id.id, "currency_id": payment.currency_id.id,
                "amount": payment.collection_net_amount, "actor_id": collector.id,
                "to_name": employee.name or collector.name, "stage": "collected",
            })

    def _transfer_cash(self, stage, actor):
        self.ensure_one()
        payment = self.sudo()
        self.env.cr.execute("SELECT id FROM account_payment WHERE id=%s FOR UPDATE", [payment.id])
        payment.invalidate_recordset(["cash_stage", "cash_holder_user_id", "cash_holder_employee_id", "state"])
        if not payment._cash_can_transfer(actor):
            raise AccessError(_("Only the current cash holder or an accounting manager can hand over this cash."))
        if actor.id != SUPERUSER_ID and payment.company_id not in actor.company_ids:
            raise AccessError(_("This cash payment belongs to another company."))
        collector = payment.cash_collector_employee_id or payment._cash_employee_for(payment.cash_collector_user_id)
        if not collector:
            raise UserError(_("Link the collector to one employee in this company before handing over cash."))
        if stage == "coach":
            if payment.cash_stage != "collected":
                raise UserError(_("Cash can be sent to the coach only from the collector."))
            target = collector.coach_id
        elif stage == "manager":
            if payment.cash_stage == "manager":
                raise UserError(_("This cash is already with the manager."))
            if payment.cash_stage == "collected" and collector.coach_id and collector.coach_id != collector.parent_id:
                raise UserError(_("Hand over cash to the coach before sending it to the manager."))
            target = collector.parent_id
        elif stage == "collected":
            if payment.cash_stage == "collected":
                raise UserError(_("This cash is already with the collector."))
            target = collector
        else:
            raise UserError(_("Unknown cash handover step."))
        if not target or not target.active or target.company_id != payment.company_id:
            raise UserError(_("Configure the collector's coach and manager in the same company."))
        if target == payment.cash_holder_employee_id:
            raise UserError(_("The recipient already holds this cash."))
        old_name = payment.cash_holder_name
        payment._cash_write_state({"cash_collector_employee_id": collector.id, "cash_holder_employee_id": target.id,
                                   "cash_holder_user_id": target.user_id.id, "cash_stage": stage})
        self.env["cash.custody.transfer"].sudo().create({
            "payment_id": payment.id, "company_id": payment.company_id.id, "currency_id": payment.currency_id.id,
            "amount": payment.collection_net_amount, "actor_id": actor.id,
            "from_name": old_name, "to_name": target.name, "stage": stage,
        })
        return True

    def action_send_cash_to_coach(self):
        self.check_access_rights("read")
        self.check_access_rule("read")
        return self._transfer_cash("coach", self.env.user)

    def action_send_cash_to_manager(self):
        self.check_access_rights("read")
        self.check_access_rule("read")
        return self._transfer_cash("manager", self.env.user)

    def action_return_cash_to_collector(self):
        self.check_access_rights("read")
        self.check_access_rule("read")
        return self._transfer_cash("collected", self.env.user)

    def _check_cash_reset(self):
        if self.ids:
            self.env.cr.execute("SELECT id FROM account_payment WHERE id IN %s ORDER BY id FOR UPDATE", [tuple(self.ids)])
            self.invalidate_recordset(["cash_stage"])
        if self.filtered(lambda pay: pay.cash_stage in ("coach", "manager")):
            raise UserError(_("Return cash to the collector before resetting or cancelling this payment."))

    def _clear_cash_current_state(self):
        for payment in self.filtered("cash_stage"):
            payment._cash_write_state({"cash_stage": False, "cash_holder_employee_id": False, "cash_holder_user_id": False})

    def _create_paired_internal_transfer_payment(self):
        for payment in self:
            super(AccountPayment, payment.with_context(
                default_cash_collector_user_id=payment.cash_collector_user_id.id
            ))._create_paired_internal_transfer_payment()


class AccountMove(models.Model):
    _inherit = "account.move"

    def _post(self, soft=True):
        posted = super()._post(soft=soft)
        posted.payment_id._initialize_cash_custody()
        posted.payment_id._sync_collection_allocations()
        return posted

    def button_draft(self):
        self.payment_id._check_cash_reset()
        result = super().button_draft()
        self.payment_id._clear_cash_current_state()
        self.payment_id._sync_collection_allocations()
        return result

    def button_cancel(self):
        self.payment_id._check_cash_reset()
        result = super().button_cancel()
        self.payment_id._clear_cash_current_state()
        self.payment_id._sync_collection_allocations()
        return result


class SaleOrderPayment(models.Model):
    _inherit = "sale.order.payment"

    cash_holder_name = fields.Char(related="account_payment_id.cash_holder_name")
    cash_stage = fields.Selection(related="account_payment_id.cash_stage")
    cash_transfer_ids = fields.One2many(related="account_payment_id.cash_transfer_ids")
    can_handover_cash = fields.Boolean(compute="_compute_cash_controls")

    @api.depends("account_payment_id.state", "account_payment_id.cash_stage", "account_payment_id.cash_holder_user_id")
    @api.depends_context("uid")
    def _compute_cash_controls(self):
        for allocation in self:
            allocation.can_handover_cash = bool(allocation.account_payment_id and allocation.account_payment_id.sudo()._cash_can_transfer(self.env.user))

    def _handover_cash(self, stage):
        self.ensure_one()
        self.check_access_rights("read")
        self.check_access_rule("read")
        if not self.account_payment_id:
            raise UserError(_("Confirm the cash payment before handing it over."))
        return self.account_payment_id._transfer_cash(stage, self.env.user)

    def action_send_cash_to_coach(self):
        return self._handover_cash("coach")

    def action_send_cash_to_manager(self):
        return self._handover_cash("manager")

    def action_return_cash_to_collector(self):
        return self._handover_cash("collected")
